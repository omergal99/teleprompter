export const t = (k) => D[lang][k] ?? k;
export const getLang = () => lang;
export function applyLang(l) {
  lang = l;
  const h = document.documentElement;
  h.lang = l;
  h.dir = l === "he" ? "rtl" : "ltr";
  document
    .querySelectorAll("[data-i18n]")
    .forEach((e) => (e.textContent = t(e.dataset.i18n)));
}
